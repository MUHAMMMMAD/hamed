/** نص مضغوط يُحقن في موجّه النظام لكل محركات الذكاء الاصطناعي. */
export function knowledgeBase(): string {
  return `
# الشركة
${company.legalName} (${company.nameEn}) — شعارها: "${company.tagline}".
تأسست ${company.founded}، ${company.classification}.
المقر: ${company.address}. الهاتف: ${company.phone}. واتساب: ${company.whatsapp}. البريد: ${company.email}.
ساعات العمل: ${company.workingHours}. مدن التنفيذ: ${company.cities.join("، ")}.
الأرقام: ${stats.map((s) => `${s.label} ${s.value}`).join("، ")}.

# الخدمات
${services.map((s) => `- ${s.title}: ${s.description} أبرز البنود: ${s.points.join("؛ ")}.`).join("\n")}

# مشاريع منجزة
${projects
  .map(
    (p) =>
      `- ${p.title} (${p.category}، ${p.city}، ${p.year}): ${p.area}، مدة ${p.duration}. ${p.summary} ميزة: ${p.highlight}.`,
  )
  .join("\n")}

# منهجية العمل
${processSteps.map((s) => `${s.n} ${s.title}: ${s.desc}`).join("\n")}

# الضمانات
${guarantees.map((g) => `- ${g.title}: ${g.desc}`).join("\n")}

# أسئلة متكررة
${faqs.map((f) => `س: ${f.q}\nج: ${f.a}`).join("\n")}
`.trim();
}
